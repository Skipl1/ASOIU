"""Подробная инструкция приготовления для локального генератора рецептов.

Для каждого ингредиента подбирается шаблон по названию и категории (способ обработки, температура,
время, признаки готовности). Шаги выстраиваются от самого долгого этапа к короткому, затем —
сборка блюда, подача и хранение.
"""

from dataclasses import dataclass

from app.services.llm.base import ContextIngredient


@dataclass(frozen=True)
class Step:
    text: str
    minutes: int
    oven: bool = False


def _has(name: str, *keys: str) -> bool:
    n = name.lower()
    return any(k in n for k in keys)


def _head(i: ContextIngredient, mass: float, extra: str = "") -> str:
    return f"{i.name} ({mass:.0f} г{extra})"


def protein_step(i: ContextIngredient, m: float) -> Step:
    n, h = i.name, _head(i, m)
    if _has(n, "яичный белок"):
        return Step(f"{h}: взбейте вилкой со щепоткой соли и приготовьте омлет на антипригарной сковороде под крышкой "
                    "на среднем огне 4–5 минут.", 6)
    if _has(n, "яйц"):
        return Step(f"{_head(i, m, f', около {max(1, round(m / 55))} шт.')}: опустите в кипящую воду и варите 9 минут, "
                    "затем переложите в холодную воду на 2 минуты, очистите и разрежьте пополам. Вместо варки можно "
                    "приготовить омлет на антипригарной сковороде под крышкой 5–6 минут.", 12)
    if _has(n, "курин", "индейк"):
        return Step(f"{h}: обсушите бумажным полотенцем, при необходимости отбейте до толщины 1,5–2 см, натрите солью, "
                    "чёрным перцем и паприкой. Выложите на противень с пергаментом и запекайте при 200 °C 18–22 минуты "
                    "до прозрачного сока при проколе. Дайте отдохнуть 5 минут и нарежьте ломтиками.", 25, True)
    if _has(n, "говядин"):
        return Step(f"{h}: обсушите, посолите и поперчите. Обжарьте на раскалённой сковороде по 3–4 минуты с каждой стороны, "
                    "затем доведите в духовке при 180 °C 8–10 минут. Дайте отдохнуть 5 минут и нарежьте поперёк волокон.", 25, True)
    if _has(n, "свин"):
        return Step(f"{h}: натрите солью, чесноком и травами, обжарьте со всех сторон по 2–3 минуты и запекайте при 200 °C "
                    "15–20 минут. Дайте отдохнуть 5 минут и нарежьте медальонами.", 25, True)
    if _has(n, "консерв"):
        return Step(f"{h}: слейте жидкость и разберите вилкой на крупные кусочки.", 2)
    if _has(n, "лосос", "сёмг", "семг", "форел"):
        return Step(f"{h}: выложите кожей вниз на противень с пергаментом, посолите и сбрызните лимонным соком. Запекайте при "
                    "190 °C 12–15 минут, пока мякоть не станет непрозрачной и не начнёт расслаиваться.", 15, True)
    if _has(n, "минтай", "треск"):
        return Step(f"{h}: при необходимости разморозьте, обсушите, посолите и поперчите. Запекайте при 190 °C 10–12 минут "
                    "или готовьте на пару 8–10 минут до непрозрачности мякоти.", 12, True)
    if _has(n, "тофу"):
        return Step(f"{h}: промокните бумажным полотенцем, нарежьте кубиками 2 см и обжарьте на антипригарной сковороде "
                    "6–8 минут до золотистой корочки, в конце приправьте специями.", 8)
    if _has(n, "чечевиц"):
        return Step(f"{h}: промойте, залейте холодной водой в соотношении 1:2, доведите до кипения и варите 15–20 минут "
                    "до мягкости; посолите в конце варки.", 20)
    if _has(n, "нут"):
        return Step(f"{h}: замочите заранее на 8–12 часов, затем варите в свежей воде 60–90 минут до мягкости и посолите "
                    "в конце (можно заменить консервированным нутом).", 60)
    if _has(n, "хумус"):
        return Step(f"{h}: выложите в отдельную пиалу и подавайте как соус.", 1)
    if _has(n, "батончик"):
        return Step(f"{h}: нарежьте на порционные кусочки и подавайте как перекус к основному блюду.", 1)
    return Step(f"{h}: приготовьте на пару или запеките при 190 °C 15–20 минут до готовности.", 20, True)


def breakfast_protein_step(i: ContextIngredient, m: float) -> Step:
    n, h = i.name, _head(i, m)
    if _has(n, "протеин"):
        return Step(f"{h}: размешайте в 150–200 мл воды или вмешайте в кашу, остывшую до 50–60 °C, до однородности "
                    "(в горячей каше протеин сворачивается).", 2)
    if _has(n, "творог"):
        return Step(f"{h}: разомните вилкой и выложите поверх основы.", 2)
    if _has(n, "молоко"):
        return Step(f"{h}: используйте вместо воды для запаривания хлопьев или добавьте в готовую кашу.", 2)
    if _has(n, "йогурт", "кефир"):
        return Step(f"{h}: используйте как заправку — полейте основу перед подачей.", 1)
    if _has(n, "сыр"):
        return Step(f"{h}: нарежьте или натрите и добавьте при подаче.", 2)
    return Step(f"{h}: добавьте к основе при подаче.", 1)


def carb_step(i: ContextIngredient, m: float) -> Step:
    n, h = i.name, _head(i, m)
    if _has(n, "гречк"):
        return Step(f"{h}: промойте 2–3 раза холодной водой, залейте водой в соотношении 1:2, доведите до кипения, посолите "
                    "и варите под крышкой на слабом огне 15–18 минут до полного впитывания воды. Снимите с огня и дайте "
                    "постоять 5 минут.", 22)
    if _has(n, "бурый рис"):
        return Step(f"{h}: промойте, залейте водой в соотношении 1:2,5, доведите до кипения и варите под крышкой на слабом "
                    "огне 30–35 минут. Снимите с огня и дайте настояться 10 минут.", 40)
    if _has(n, "хлебцы"):
        return Step(f"{h}: используйте как есть — в качестве хрустящей основы.", 0)
    if _has(n, "рис"):
        return Step(f"{h}: промойте до прозрачной воды, залейте водой в соотношении 1:2 и варите под крышкой 15–18 минут, "
                    "затем дайте постоять 5 минут.", 20)
    if _has(n, "киноа"):
        return Step(f"{h}: промойте в сите, залейте водой 1:2 и варите 12–15 минут, пока зёрна не станут прозрачными, "
                    "а вода не впитается.", 15)
    if _has(n, "булгур"):
        return Step(f"{h}: прогрейте 1–2 минуты на сухой сковороде, залейте горячей водой 1:2 и варите под крышкой "
                    "10–12 минут.", 14)
    if _has(n, "макарон"):
        return Step(f"{h}: отварите в большом количестве подсоленной воды (около 1 л на 100 г) 8–10 минут до состояния "
                    "al dente и откиньте на дуршлаг.", 12)
    if _has(n, "гранола"):
        return Step(f"{h}: используйте без варки как основу или посыпку.", 1)
    if _has(n, "хлопь"):
        return Step(f"{h}: залейте горячей водой в соотношении 1:2, накройте и оставьте на 5–7 минут "
                    "(или варите 3–4 минуты, помешивая).", 7)
    if _has(n, "хлеб"):
        return Step(f"{h}: подсушите в тостере или на сухой сковороде 1–2 минуты.", 3)
    if _has(n, "картоф", "батат"):
        return Step(f"{h}: вымойте, нарежьте дольками толщиной 1,5–2 см, приправьте солью и паприкой, выложите на противень "
                    "с пергаментом и запекайте при 200 °C 25–30 минут, перевернув в середине.", 30, True)
    if _has(n, "банан"):
        return Step(f"{h}: очистите и нарежьте кружками.", 2)
    if _has(n, "черник", "клубник"):
        return Step(f"{h}: промойте и обсушите бумажным полотенцем.", 2)
    if _has(n, "изюм", "финик"):
        return Step(f"{h}: промойте, залейте тёплой водой на 5 минут, обсушите и мелко нарежьте.", 6)
    if i.category_code == "cat_fruits":
        return Step(f"{h}: вымойте, очистите при необходимости и нарежьте небольшими кусочками.", 3)
    return Step(f"{h}: отварите до готовности 15–20 минут.", 20)


def veg_step(i: ContextIngredient, m: float) -> Step:
    n, h = i.name, _head(i, m)
    if _has(n, "брокколи", "цветн"):
        return Step(f"{h}: разберите на соцветия и готовьте на пару 5–6 минут до мягкости и яркого цвета "
                    "(или бланшируйте 3 минуты в кипящей подсоленной воде).", 7)
    if _has(n, "шпинат"):
        return Step(f"{h}: промойте и обсушите; подавайте свежим или прогрейте на сковороде 1–2 минуты до увядания.", 3)
    if _has(n, "помидор"):
        return Step(f"{h}: вымойте и нарежьте дольками.", 2)
    if _has(n, "огур"):
        return Step(f"{h}: вымойте и нарежьте полукружьями.", 2)
    if _has(n, "перец"):
        return Step(f"{h}: удалите семена и нарежьте полосками; подавайте свежим или обжарьте на сухой сковороде 4–5 минут.", 5)
    if _has(n, "морков"):
        return Step(f"{h}: очистите, нарежьте кружками и готовьте на пару 8–10 минут.", 10)
    if _has(n, "кабач"):
        return Step(f"{h}: нарежьте кружками толщиной 1 см и обжарьте на разогретой антипригарной сковороде "
                    "по 2–3 минуты с каждой стороны.", 6)
    if _has(n, "фасоль"):
        return Step(f"{h}: отварите в подсоленной воде 5–6 минут и откиньте на дуршлаг.", 6)
    if _has(n, "лук"):
        return Step(f"{h}: нарежьте полукольцами и обжарьте до золотистого цвета 5–7 минут.", 7)
    if _has(n, "шампиньон", "гриб"):
        return Step(f"{h}: нарежьте пластинами и обжарьте на сухой сковороде 7–8 минут, пока не испарится жидкость.", 8)
    if _has(n, "тыкв"):
        return Step(f"{h}: нарежьте кубиками 2 см и запекайте при 200 °C 20–25 минут до мягкости.", 25, True)
    return Step(f"{h}: нарежьте и потушите с небольшим количеством воды 5–7 минут.", 7)


def fat_step(i: ContextIngredient, m: float) -> Step:
    n = i.name
    if _has(n, "масло"):
        return Step(f"{_head(i, m, f', около {max(1, round(m / 5))} ч. л.')}: заправьте готовое блюдо перед подачей; "
                    "немного можно использовать для смазывания противня.", 0)
    if _has(n, "авокадо"):
        return Step(f"{_head(i, m)}: разрежьте пополам, удалите косточку, нарежьте ломтиками и выложите перед подачей.", 2)
    if _has(n, "чиа", "льн", "лён"):
        return Step(f"{_head(i, m)}: посыпьте блюдо перед подачей (семена чиа можно заранее замочить в воде на 10 минут).", 0)
    return Step(f"{_head(i, m)}: обжарьте на сухой сковороде 2–3 минуты до аромата, крупно измельчите и посыпьте блюдо "
                "перед подачей.", 3)


def _is_soft_protein(i: ContextIngredient) -> bool:
    return i.category_code == "cat_dairy" or _has(i.name, "протеин")


def omelette_egg_step(i: ContextIngredient, m: float) -> Step:
    return Step(f"{_head(i, m, f', около {max(1, round(m / 55))} шт.')}: взбейте вилкой со щепоткой соли и перца, "
                "залейте овощи на сковороде и готовьте под крышкой на слабом огне 5–6 минут, пока омлет не схватится.", 7)


def omelette_veg_step(i: ContextIngredient, m: float) -> Step:
    return Step(f"{_head(i, m)}: нарежьте небольшими кусочками и обжарьте на разогретой сковороде 2–3 минуты, помешивая.", 4)


def compose(items: list[tuple[str, ContextIngredient, float]], style: str) -> tuple[list[str], int]:
    """Шаги инструкции и общее время приготовления, мин.

    style: hot — горячее с гарниром; porridge — каша/завтрак-основа; omelette — омлет; snack — перекус.
    """
    has_oil = any(_has(ing.name, "масло") for _, ing, _ in items)
    composition = ", ".join(f"{ing.name.lower()} — {mass:.0f} г" for _, ing, mass in items)
    prep = f"Подготовка: отмерьте продукты по составу ({composition}), вымойте овощи и фрукты."

    if style == "omelette":
        # Порядок важен: масло → овощи → яйца → хлеб/фрукты
        steps = [prep]
        for _, ing, mass in items:
            if _has(ing.name, "масло"):
                steps.append(f"{_head(ing, mass)}: разогрейте на антипригарной сковороде на среднем огне.")
        cooking = [omelette_veg_step(ing, mass) for role, ing, mass in items if role == "veg"]
        cooking += [omelette_egg_step(ing, mass) for role, ing, mass in items if role == "egg"]
        cooking += [carb_step(ing, mass) for role, ing, mass in items if role in ("carb", "carb2")]
        steps += [s.text for s in cooking]
        steps.append("Сборка: переложите омлет на тарелку, рядом выложите хлеб или фрукты; посыпьте зеленью по вкусу.")
        steps.append("Подача: подавайте сразу, пока омлет горячий.")
        return steps, 10 + sum(s.minutes for s in cooking[:2])

    cooking: list[Step] = []
    finishing: list[Step] = []
    for role, ing, mass in items:
        if role in ("carb", "carb2"):
            cooking.append(carb_step(ing, mass))
        elif role in ("protein", "egg"):
            soft = style in ("porridge", "snack") and (_is_soft_protein(ing) or _has(ing.name, "батончик", "хумус"))
            cooking.append(breakfast_protein_step(ing, mass) if soft and _is_soft_protein(ing) else protein_step(ing, mass))
        elif role == "veg":
            cooking.append(veg_step(ing, mass))
        else:
            finishing.append(fat_step(ing, mass))
    cooking.sort(key=lambda s: -s.minutes)

    if any(s.oven for s in cooking):
        prep += " Разогрейте духовку до 200 °C."
    if len(cooking) > 1 and cooking[0].minutes >= 15:
        first = cooking[0].text.split(" (", 1)[0].lower()
        prep += f" Начните с самого долгого этапа — «{first}», остальное готовьте параллельно."

    if style == "porridge":
        assembly = "Сборка: переложите кашу в миску, сверху выложите фрукты и добавки. При желании приправьте корицей."
        serving = "Подача: подавайте сразу. Кашу можно приготовить с вечера и хранить в холодильнике до 2 суток."
    elif style == "snack":
        assembly = "Сборка: разложите продукты на тарелке или в контейнере — перекус удобно взять с собой."
        serving = "Хранение: в холодильнике до 1 суток; фрукты нарезайте непосредственно перед едой, чтобы они не потемнели."
    else:
        dressed = ", затем заправьте маслом" if has_oil else ""
        assembly = (f"Сборка: выложите в тарелку гарнир, рядом — белковую часть и овощи{dressed}. "
                    "Приправьте солью, свежемолотым перцем и зеленью по вкусу, при желании сбрызните лимонным соком.")
        serving = ("Подача и хранение: подавайте сразу, пока блюдо тёплое. Для заготовки впрок остудите, разложите "
                   "по контейнерам и храните в холодильнике до 3 суток; разогревайте 2–3 минуты в микроволновой печи.")

    steps = [prep] + [s.text for s in cooking] + [s.text for s in finishing] + [assembly, serving]
    total = 10 + max((s.minutes for s in cooking), default=0) + 5
    return steps, total
